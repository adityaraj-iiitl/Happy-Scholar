import React, { useState, useEffect } from 'react';
import { 
  ShoppingBag, 
  Sparkles, 
  Loader2, 
  AlertCircle, 
  ExternalLink,
  Moon,
  BookOpen,
  Activity,
  Utensils,
  Eye,
  Clock,
  Heart,
  Laptop,
  Book,
  Coffee,
  RotateCw
} from 'lucide-react';
import { api } from '../services/api';

// Map categories to visual icons and border gradients
const CATEGORY_MAP = {
  'Sleep Improvement': { icon: Moon, color: 'text-indigo-500 bg-indigo-500/10 border-indigo-500/20' },
  'Study Essentials': { icon: BookOpen, color: 'text-violet-500 bg-violet-500/10 border-violet-500/20' },
  'Fitness': { icon: Activity, color: 'text-emerald-500 bg-emerald-500/10 border-emerald-500/20' },
  'Nutrition': { icon: Utensils, color: 'text-emerald-400 bg-emerald-400/10 border-emerald-400/20' },
  'Eye Care': { icon: Eye, color: 'text-sky-500 bg-sky-500/10 border-sky-500/20' },
  'Productivity': { icon: Clock, color: 'text-amber-500 bg-amber-500/10 border-amber-500/20' },
  'Mental Wellness': { icon: Heart, color: 'text-rose-500 bg-rose-500/10 border-rose-500/20' },
  'Workspace Setup': { icon: Laptop, color: 'text-indigo-400 bg-indigo-400/10 border-indigo-400/20' },
  'Books': { icon: Book, color: 'text-blue-500 bg-blue-500/10 border-blue-500/20' },
  'Healthy Snacks': { icon: Coffee, color: 'text-amber-600 bg-amber-600/10 border-amber-600/20' }
};

const getConfidenceBadgeColor = (c) => {
  switch (c) {
    case 'Highly Recommended':
      return 'bg-rose-500/10 text-rose-700 dark:text-rose-300 border border-rose-500/25';
    case 'Recommended':
      return 'bg-indigo-500/10 text-indigo-700 dark:text-indigo-300 border border-indigo-500/25';
    default:
      return 'bg-slate-500/10 text-slate-500 dark:text-slate-400 border border-slate-500/20';
  }
};

function Recommendations() {
  const [recommendations, setRecommendations] = useState([]);
  const [loading, setLoading] = useState(true);
  const [refreshing, setRefreshing] = useState(false);
  const [error, setError] = useState('');

  const fetchRecommendations = async (refresh = false) => {
    if (refresh) {
      setRefreshing(true);
    } else {
      setLoading(true);
    }
    setError('');
    try {
      const data = await api.getProductRecommendations(refresh);
      setRecommendations(data || []);
    } catch (err) {
      setError(err.message || 'Failed to fetch product recommendations.');
    } finally {
      setLoading(false);
      setRefreshing(false);
    }
  };

  useEffect(() => {
    fetchRecommendations(false);
  }, []);

  return (
    <div className="max-w-6xl mx-auto space-y-10">
      {/* Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-6 pb-2 border-b border-slate-200/60 dark:border-slate-800/40">
        <div className="space-y-1.5">
          <h1 className="text-3xl md:text-[42px] font-bold text-slate-900 dark:text-white tracking-tight leading-tight flex items-center gap-3">
            <span>🛍 Recommended For You</span>
          </h1>
          <p className="text-slate-500 dark:text-slate-400 text-sm md:text-base">
            Personalized product suggestions generated by Gemini AI based on your lifestyle.
          </p>
        </div>

        <button
          onClick={() => fetchRecommendations(true)}
          disabled={loading || refreshing}
          className="flex items-center gap-2.5 px-6 py-3 bg-gradient-to-r from-indigo-600 to-violet-600 hover:from-indigo-500 hover:to-violet-500 text-white font-bold rounded-xl text-sm transition-all hover:scale-[1.02] active:scale-98 shadow-md shadow-indigo-600/10 hover:shadow-indigo-600/25 cursor-pointer shrink-0 disabled:opacity-50"
        >
          {refreshing ? (
            <Loader2 className="h-5 w-5 animate-spin" />
          ) : (
            <RotateCw className="h-5 w-5" />
          )}
          <span>Refresh Recommendations</span>
        </button>
      </div>

      {error && (
        <div className="p-4 bg-rose-50 dark:bg-rose-950/20 border border-rose-200 dark:border-rose-900/50 text-rose-800 dark:text-rose-300 rounded-2xl flex items-center gap-3 shadow-xs">
          <AlertCircle className="h-5 w-5 shrink-0" />
          <span className="font-semibold text-sm">{error}</span>
        </div>
      )}

      {loading ? (
        <div className="flex flex-col items-center justify-center py-20">
          <Loader2 className="h-10 w-10 text-indigo-500 animate-spin" />
          <p className="text-slate-400 text-sm mt-3 font-semibold animate-pulse">Running lifestyle compatibility check...</p>
        </div>
      ) : recommendations.length === 0 ? (
        <div className="bg-white dark:bg-slate-900 border border-slate-200/80 dark:border-slate-800/80 rounded-2xl p-12 text-center text-slate-400 shadow-premium">
          No recommendations available. Please log habits for at least one day so Gemini can understand your lifestyle.
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
          {recommendations.map((item, idx) => {
            const catDetails = CATEGORY_MAP[item.category] || { icon: ShoppingBag, color: 'text-indigo-500 bg-indigo-500/10 border-indigo-500/20' };
            const Icon = catDetails.icon;

            return (
              <div 
                key={item.id || idx}
                className="bg-white dark:bg-slate-900 border border-slate-200/80 dark:border-slate-800/80 rounded-2xl p-6 shadow-premium hover:-translate-y-1.5 hover:shadow-premium-hover transition-premium flex flex-col justify-between"
              >
                <div className="space-y-4">
                  {/* Category icon header */}
                  <div className="flex items-center justify-between">
                    <div className={`h-11 w-11 rounded-xl ${catDetails.color} flex items-center justify-center border shadow-xs`}>
                      <Icon className="h-5.5 w-5.5" />
                    </div>
                    <span className={`text-[10px] px-2.5 py-0.5 rounded-full font-bold uppercase tracking-wider ${getConfidenceBadgeColor(item.confidence)}`}>
                      {item.confidence}
                    </span>
                  </div>

                  {/* Product Details */}
                  <div className="space-y-2">
                    <h3 className="text-lg font-bold text-slate-900 dark:text-white leading-snug">{item.name}</h3>
                    <span className="inline-block text-xs font-semibold px-2 py-0.5 bg-slate-100 dark:bg-slate-800 text-slate-600 dark:text-slate-400 rounded-md">
                      {item.category}
                    </span>
                    <p className="text-sm text-slate-500 dark:text-slate-400 leading-relaxed font-medium pt-1">
                      {item.reason}
                    </p>
                  </div>
                </div>

                {/* Footer price & shop buttons */}
                <div className="mt-6 pt-4 border-t border-slate-100 dark:border-slate-800/60 space-y-4">
                  <div className="flex items-center justify-between">
                    <span className="text-xs text-slate-500 dark:text-slate-400 font-semibold uppercase tracking-wider">Est. Price</span>
                    <span className="text-xl font-extrabold text-slate-950 dark:text-white">{item.estimated_price}</span>
                  </div>

                  <div className="flex gap-2">
                    <a
                      href={item.amazon_search}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="flex-1 flex items-center justify-center gap-1.5 py-2.5 px-3 bg-amber-500/10 hover:bg-amber-500 text-amber-800 dark:text-amber-300 hover:text-white border border-amber-500/20 hover:border-transparent rounded-xl text-xs font-bold transition-all hover:scale-[1.02] active:scale-98 cursor-pointer text-center"
                    >
                      <span>Amazon</span>
                      <ExternalLink className="h-3 w-3 shrink-0" />
                    </a>
                    
                    <a
                      href={item.flipkart_search}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="flex-1 flex items-center justify-center gap-1.5 py-2.5 px-3 bg-blue-500/10 hover:bg-blue-600 text-blue-600 dark:text-blue-400 hover:text-white border border-blue-500/20 hover:border-transparent rounded-xl text-xs font-bold transition-all hover:scale-[1.02] active:scale-98 cursor-pointer text-center"
                    >
                      <span>Flipkart</span>
                      <ExternalLink className="h-3 w-3 shrink-0" />
                    </a>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}

export default Recommendations;
